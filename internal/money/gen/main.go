// Command gen writes internal/money/iso4217.go from the ISO 4217 list published by
// SIX, the maintenance agency: go run ./internal/money/gen [-file list-one.xml].
package main

import (
	"bytes"
	"context"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"sort"
	"strconv"
)

const source = "https://www.six-group.com/dam/download/financial-information/data-center/iso-currrency/lists/list-one.xml"

type list struct {
	Published string `xml:"Pblshd,attr"`
	Entries   []struct {
		Code  string `xml:"Ccy"`
		Minor string `xml:"CcyMnrUnts"`
	} `xml:"CcyTbl>CcyNtry"`
}

func main() {
	file := flag.String("file", "", "read the list from this file instead of downloading it")
	out := flag.String("out", "internal/money/iso4217.go", "output file")
	flag.Parse()

	data, err := read(*file)
	if err != nil {
		log.Fatal(err)
	}
	var l list
	if err := xml.Unmarshal(data, &l); err != nil {
		log.Fatal(err)
	}
	exponents := map[string]int{}
	for _, e := range l.Entries {
		n, err := strconv.Atoi(e.Minor)
		if e.Code == "" || err != nil {
			continue // funds and metals have "N.A."
		}
		exponents[e.Code] = n
	}
	codes := make([]string, 0, len(exponents))
	for c := range exponents {
		codes = append(codes, c)
	}
	sort.Strings(codes)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by go run ./internal/money/gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package money\n\n")
	fmt.Fprintf(&b, "// iso4217Published is the publication date of the ISO 4217 list this table was built from.\n")
	fmt.Fprintf(&b, "const iso4217Published = %q\n\n", l.Published)
	fmt.Fprintf(&b, "// iso4217 maps a currency code to its number of minor-unit digits.\n")
	fmt.Fprintf(&b, "var iso4217 = map[string]int{\n")
	for _, c := range codes {
		fmt.Fprintf(&b, "\t%q: %d,\n", c, exponents[c])
	}
	fmt.Fprintf(&b, "}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile(*out, src, 0o644); err != nil {
		log.Fatal(err)
	}
}

func read(file string) ([]byte, error) {
	if file != "" {
		return os.ReadFile(file)
	}
	req, err := http.NewRequestWithContext(context.Background(), http.MethodGet, source, http.NoBody)
	if err != nil {
		return nil, err
	}
	resp, err := http.DefaultClient.Do(req)
	if err != nil {
		return nil, err
	}
	defer func() { _ = resp.Body.Close() }()
	if resp.StatusCode != http.StatusOK {
		return nil, fmt.Errorf("GET %s: %s", source, resp.Status)
	}
	return io.ReadAll(resp.Body)
}
